def seed_database(db: Session) -> int:
    """Insert seed tickers. Returns number of tickers added.

    No events are seeded here — catalyst events come exclusively from the
    scrapers hitting official government sources.
    """
    count = 0
    for t in SEED_TICKERS:
        existing = db.query(Ticker).filter(Ticker.ticker == t["ticker"]).first()
        if not existing:
            db.add(Ticker(**t))
            count += 1

    db.commit()
    return count
